/* ============== 当前语言 ============== */
let CURRENT_LANG = 'zh';
try { CURRENT_LANG = localStorage.getItem('zb_admin_lang') || 'zh'; } catch (e) {}

/* ============== 翻译函数 ============== */
function t(key, params) {
  const dict = I18N[CURRENT_LANG] || I18N.zh;
  let str = dict[key];
  if (str === undefined) str = (I18N.zh[key] || key);  // 回退中文 → key
  if (params) {
    Object.keys(params).forEach((k) => {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k]);
    });
  }
  return str;
}

/* ============== 切换语言（刷新页面应用） ============== */
function setLang(lang) {
  if (lang === CURRENT_LANG) return;
  try { localStorage.setItem('zb_admin_lang', lang); } catch (e) {}
  window.location.reload();
}

